/* ---------- 引擎：時光機 ---------- */
function timeLab(name, intro, c) {
  const Y = c.years || (() => { const a = []; for (let y = c.min; y <= c.max; y += c.step || 1) a.push(y); return a; })();
  const fmt = c.fmt || (y => (y < 0 ? '西元前 ' + (-y) : '西元 ' + y) + ' 年');
  const ix = y => { const i = Y.indexOf(y); if (i < 0) throw new Error(name + '：時間軸上沒有 ' + y); return i; };
  const X = k => 14 + 292 * k / (Y.length - 1), yr = s => Y[s.k];
  return { name, intro,
    init: () => ({ k: ix(c.start) }),
    ctrl: [{ k: 'k', label: '時間', min: 0, max: Y.length - 1, step: 1, fmt: k => fmt(Y[k]) }],
    view: s => {
      const y = yr(s), cur = bandOf(c.bands, y); let g = '';
      c.bands.forEach(b => {
        const ks = Y.map((v, i) => v >= b[0] && v < b[1] ? i : -1).filter(i => i >= 0); if (!ks.length) return;
        const a = X(ks[0]) - 5, w = X(ks[ks.length - 1]) - X(ks[0]) + 10;
        g += `<rect x="${a}" y="30" width="${w}" height="18" rx="5" fill="${b[3] || '#3b4a8a'}" opacity="${b === cur ? 1 : .38}"/>` + (w >= 34 ? T(a + w / 2, 39, b[2], 'class="bl"') : '');
      });
      c.events.forEach(e => { const k = Y.indexOf(e[0]); if (k >= 0) g += `<circle cx="${X(k)}" cy="16" r="${e[0] === y ? 6 : 3.5}" class="${e[0] === y ? 'evon' : 'ev'}"/>`; });
      g += `<line x1="${X(s.k)}" y1="24" x2="${X(s.k)}" y2="54" class="ln2"/>` + T(X(s.k), 62, '▲', 'class="tk"');
      const ev = c.events.find(e => e[0] === y);
      return svg(320, 68, g) + `<div class="tscene"><div class="emo big">${c.scene(y, cur)}</div><div class="tev">${ev ? `${ev[1]} <b>${esc(ev[2])}</b>` : '<span class="mute">（這個時間點沒有標記的大事）</span>'}</div></div>`;
    },
    read: s => [['時代', (bandOf(c.bands, yr(s)) || [0, 0, '—'])[2]]].concat(c.rows(yr(s))),
    missions: c.missions.map(([t, cond, say, solY, hint, startY]) => M(t, s => { s.k = ix(startY !== undefined ? startY : c.start); }, s => cond(yr(s)), say, s => { s.k = ix(solY); },
      hint || '慢慢移動時間軸（也可以按 − ＋ 一格一格調），注意下面每一欄什麼時候改變。'))
  };
}

/* ---------- 引擎：線索偵探（點出文中可疑或特別的字句） ----------
   文字格式：{顯示文字|說明}　目標加上 |*：{顯示文字|說明|*} */
function huntLab(name, intro, docs) {
  const P = docs.map(d => { const toks = [], re = /\{([^|}]+)\|([^|}]*)(\|\*)?\}|([^{]+)/g; let m;
    while ((m = re.exec(d.text))) toks.push(m[4] !== undefined ? { t: m[4] } : { t: m[1], n: m[2], hit: !!m[3] });
    return { ...d, toks, need: toks.filter(t => t.hit).length }; });
  return { name, intro,
    init: () => ({ d: 0, found: {}, note: -1 }),
    view: s => { const D = P[s.d];
      return `<div class="hunt">${D.head ? `<div class="hhead">${esc(D.head)}</div>` : ''}<div class="hbody">` + D.toks.map((t, i) => t.n === undefined ? esc(t.t).replace(/\n/g, '<br>')
        : `<span class="ht${s.found[i] ? ' hf' : ''}${s.note === i ? ' hn' : ''}" data-tap="${i}">${esc(t.t).replace(/\n/g, '<br>')}</span>`).join('') + '</div></div>'; },
    read: s => { const D = P[s.d], t = D.toks[s.note];
      return [['已找到', `${Object.keys(s.found).length} / ${D.need}`], t ? ['「' + esc(t.t.length > 14 ? t.t.slice(0, 14) + '…' : t.t) + '」', esc(t.n)] : ['提示', '點有虛線的字句，看看說明']]; },
    tap: (s, id) => { const t = P[s.d].toks[+id]; if (!t || t.n === undefined) return; s.note = +id; if (t.hit) s.found[id] = 1; },
    missions: P.map((D, i) => M(D.m, s => { s.d = i; s.found = {}; s.note = -1; }, s => s.d === i && Object.keys(s.found).length >= D.need, D.say,
      s => { D.toks.forEach((t, k) => { if (t.hit) s.found[k] = 1; }); }, D.hint || '每個有虛線的地方都點點看，讀一下說明。'))
  };
}

/* ---------- 引擎：地圖釘（點地點看說明） ---------- */
function pinLab(name, intro, bg, pts, missions) {
  return { name, intro, init: () => ({ p: '' }),
    view: s => bg(pts.map(p => `<g data-tap="${p.id}" class="pin${s.p === p.id ? ' on' : ''}"><circle cx="${p.x}" cy="${p.y}" r="12" class="hit"/><circle cx="${p.x}" cy="${p.y}" r="5" class="dot"/>${T(p.x + (p.dx || 0), p.y + (p.dy === undefined ? -11 : p.dy), p.n, 'class="plb"')}</g>`).join('')),
    read: s => { const p = pts.find(q => q.id === s.p); return p ? [[p.n, p.f]] : [['提示', '點地圖上的圓點，看看那裡發生過什麼事']]; },
    tap: (s, id) => { s.p = id; },
    missions: missions.map(([t, id, say]) => M(t, s => { s.p = ''; }, s => s.p === id, say, s => { s.p = id; }, '每個圓點都點點看，讀一下說明。'))
  };
}

